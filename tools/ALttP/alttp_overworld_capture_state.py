#!/usr/bin/env python3
"""Capture-attested partial final-state adapter; never a complete WRAM snapshot.

Export/reverify exact raster-linked final words with the read-only capture probe.
Only a complete reusable aperture assembly may activate. Unchanged hidden guards
remain base-ROM evidence, explicitly NOT observed dispatch provenance. A source
capture SHA cannot be retargeted to another capture or supplied without reprobe.
"""
import argparse
import copy
import hashlib
import json
from collections import Counter
from pathlib import Path
import subprocess

from alttp_atlas import Rom
from alttp_overworld_geometry import (stable_digest, adjusted_attribute, behavior,
                                      review_summary)
from alttp_overworld_castle import build_rules, generate
from alttp_overworld_replay import candidate_stream


def export_manifest(base, capture, probe, origin, bg=1):
    """Return ALTPOWCAPSTATE1 from actual source raster; no fixed edits/positions.

    Origin is explicit evidence supplied by the caller, then tested against the
    entire visible field. Require >=90% exact unchanged identities to reject a
    wrong camera alignment rather than manufacturing a large overwrite patch.
    """
    capture=Path(capture); origin=list(origin)
    if len(origin)!=2 or any(type(v) is not int for v in origin):
        raise ValueError('integer map pixel origin required')
    run=subprocess.run([str(probe),str(capture),'-',*map(str,origin),str(bg),'--export-cells'],
                       input=candidate_stream(base),text=True,capture_output=True,check=True)
    observed=json.loads(run.stdout)
    if observed['rom_sha256']!=base['pin']['rom_sha256']:
        raise ValueError('source capture ROM mismatch')
    by={(p['x'],p['y']):p for p in base['placements'] if p['layer']==0 and p['surface']==0}
    cells={(p['x'],p['y']):p for p in observed['cells']}
    unchanged=sum(cell in by and p['word']==by[cell]['word'] and
                  int(p['hash'],16)==int((by[cell]['hash'] or '0').split(':')[-1],16)
                  for cell,p in cells.items())
    if not cells or unchanged/len(cells)<.9:
        raise ValueError('capture origin/graphics parity below90%; refusing inferred overwrite')
    rules=build_rules(base,base['pin'].get('floor_rise') or 32)
    family=next(f for f in rules['families'] if f['id']=='castle-open-crest-door-crosssection')
    assemblies=[]
    for cell,p in by.items():
        if p['map16_member']!=0 or p['map16']!=family['members'][0]['map16']:continue
        x,y=cell; members=[]; changes=[]
        for m in family['members']:
            key=x+m['x'],y+m['y'];q=by.get(key);v=cells.get(key)
            if (q is None or q['map16']!=m['map16'] or q['map16_member']!=m['map16_member'] or
                    (v['word'] if v else q['word'])!=m['word']):break
            members.append(list(key))
            if q['word']!=m['word']:
                if not v:break
                changes.append(dict(x=key[0],y=key[1],before_word=q['word'],
                                    word=v['word'],hash='v1:4bpp:'+format(int(v['hash'],16),'016x')))
        else:
            if changes:assemblies.append(dict(family=family['id'],origin=[x,y],
                members=members,changes=changes,
                ownership_evidence='user-attested aperture assembly; observed changed words and exact base-ROM guards; actual dispatch writer unobserved'))
    if not assemblies:raise ValueError('no fully matched observed open-aperture overwrite')
    return dict(format='ALTPOWCAPSTATE1',rom_sha256=base['pin']['rom_sha256'],
                base_provenance_sha256=base['pin']['provenance_sha256'],
                source_capture_sha256=hashlib.sha256(capture.read_bytes()).hexdigest(),
                origin=origin,bg=bg,observed_cells=len(cells),unchanged_cells=unchanged,
                assemblies=assemblies,complete_gameplay_state=False)


def generate_capture_state(base, manifest, capture, probe, core, rom):
    """Reprobe SHA-matching original, apply verified edits, solve, recount.

    Returns (candidate, rules). Geometry remains generated by shared exact
    families; the adapter supplies final state words, never numeric elevations.
    """
    if manifest.get('format')!='ALTPOWCAPSTATE1':raise ValueError('unsupported capture-state manifest')
    source=hashlib.sha256(Path(capture).read_bytes()).hexdigest()
    if source!=manifest.get('source_capture_sha256'):raise ValueError('capture-state source SHA256 mismatch')
    expected=export_manifest(base,capture,probe,manifest['origin'],manifest['bg'])
    if manifest!=expected:raise ValueError('manifest differs from source capture re-probe or base provenance')
    if rom.sha256!=base['pin']['rom_sha256']:raise ValueError('collision ROM mismatch')
    c=copy.deepcopy(base);by={(p['x'],p['y']):p for p in c['placements']}
    writer=max(p['writer'] for p in c['placements'])+1
    for assembly in manifest['assemblies']:
        for cell in assembly['members']:by[tuple(cell)]['writer']=writer
        for change in assembly['changes']:
            p=by[change['x'],change['y']];w=change['word']
            raw=rom.get_byte(0x8e9459+(w&511));attr=adjusted_attribute(raw,w)
            p.update(word=w,hash=change['hash'],map8_slot=w&1023,collision_index=w&511,
                     raw_collision=raw,collision=attr,behavior=behavior(attr),
                     flip_h=bool(w&0x4000),flip_v=bool(w&0x8000),
                     graphics_evidence='SHA-pinned original raster-linked final identity')
        writer+=1
    pin=c['pin'];pin.update(state_key='capture-attested-partial:'+source,
        capture_sha256=source,source_capture_sha256=source,
        capture_state_manifest_sha256=stable_digest(manifest),
        provenance_sha256=stable_digest([(p['word'],p['writer'],p['map16']) for p in c['placements']]))
    c['capture_state_evidence']=manifest
    c['scope']['complete_gameplay_state']=False
    c['blockers'].append('partial raster state only; unobserved final maps/dispatch/state remain base-ROM evidence')
    c,rules=generate(c,core,pin.get('floor_rise') or 32)
    c['coverage']['by_behavior']=dict(Counter(p['behavior'] for p in c['placements']))
    c['coverage']['by_graphics']=dict(Counter(p['graphics_status'] for p in c['placements']))
    return c,rules


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--base',type=Path,required=True)
    p.add_argument('--capture',type=Path,required=True)
    p.add_argument('--probe',type=Path,required=True)
    p.add_argument('--origin',type=int,nargs=2)
    p.add_argument('--bg',type=int,default=1)
    p.add_argument('--export-manifest',type=Path)
    p.add_argument('--capture-state',type=Path)
    p.add_argument('--core',type=Path)
    p.add_argument('--rom',type=Path,default=Path.home()/'Downloads/Zelda_ALTTP.zip')
    p.add_argument('--output',type=Path)
    p.add_argument('--review-summary',type=Path)
    a=p.parse_args();base=json.loads(a.base.read_text())
    if a.export_manifest:
        if a.origin is None:p.error('--origin required for export')
        m=export_manifest(base,a.capture,a.probe,a.origin,a.bg)
        a.export_manifest.write_text(json.dumps(m,indent=2)+'\n')
    if a.capture_state:
        if not a.core or not a.output:p.error('--capture-state requires --core and --output')
        c,_=generate_capture_state(base,json.loads(a.capture_state.read_text()),a.capture,
                                  a.probe,a.core,Rom(a.rom))
        a.output.write_text(json.dumps(c,separators=(',',':'))+'\n')
        if a.review_summary:a.review_summary.write_text(json.dumps(review_summary(c),indent=2)+'\n')
        print(json.dumps(dict(pin=c['pin'],coverage=c['coverage']),indent=2))
    elif not a.export_manifest:p.error('choose --export-manifest or --capture-state')


if __name__=='__main__':main()
